void	fill_perms(int perms[24][4])
{
	char	*str;
	int		i;
	int		j;

	str = "12341243132413421423143221342143"
		"23142341241324313124314232143241"
		"34123421412341324213423143124321";
	i = 0;
	while (i < 24)
	{
		j = 0;
		while (j < 4)
		{
			perms[i][j] = str[(i * 4) + j] - '0';
			j++;
		}
		i++;
	}
}
